// Builds src/geo-data.js from the "zipcodes" package (US ZIP centroids): every US city once (centroid = mean of its ZIPs)
// and every ZIP pointing at its own centroid. Run: node scripts/build-geo.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const { codes } = createRequire(import.meta.url)("zipcodes");
const cities = new Map();
const zips = [];
for (const z of Object.values(codes)) {
  if (z.country !== "US" || !z.city || !z.state || !Number.isFinite(z.latitude)) continue;
  const key = `${z.city}|${z.state}`;
  const c = cities.get(key) || { n: 0, lat: 0, lng: 0 };
  c.n++; c.lat += z.latitude; c.lng += z.longitude; cities.set(key, c);
  zips.push([z.zip, Math.round(z.latitude * 100), Math.round(z.longitude * 100)]);
}
const cityRows = [...cities].map(([k, c]) => `${k}|${Math.round((c.lat / c.n) * 100)}|${Math.round((c.lng / c.n) * 100)}`).sort();
const zipRows = zips.sort((a, b) => a[0].localeCompare(b[0])).map((z) => z.join("|"));
writeFileSync(new URL("../src/geo-data.js", import.meta.url),
  `// GENERATED by scripts/build-geo.mjs from the "zipcodes" package. Do not edit.\n// City|ST|lat*100|lng*100 and ZIP|lat*100|lng*100, one per line.\nexport const CITY_ROWS = ${JSON.stringify(cityRows.join("\n"))};\nexport const ZIP_ROWS = ${JSON.stringify(zipRows.join("\n"))};\n`);
console.log(cityRows.length, "cities,", zipRows.length, "zips");
